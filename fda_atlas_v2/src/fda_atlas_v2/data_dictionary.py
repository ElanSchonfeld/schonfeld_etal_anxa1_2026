def _fallback(column: str) -> str:
    return "Release field for " + column.replace("_", " ") + "."


def _field_description(table_name: str, column: str) -> tuple[str, bool]:
    key = (table_name, column)
    if key in TABLE_COLUMN_DESCRIPTIONS:
        return TABLE_COLUMN_DESCRIPTIONS[key], True
    if column in COLUMN_DESCRIPTIONS:
        return COLUMN_DESCRIPTIONS[column], True
    return _fallback(column), False


def build_data_dictionary(release_id: str, directory: Path) -> pd.DataFrame:
    rows = []
    for table_name in sorted(TABLE_CONTRACTS):
        path = directory / f"{table_name}.parquet"
        if table_name == "data_dictionary" or not path.is_file():
            continue
        frame = pd.read_parquet(path)
        contract = TABLE_CONTRACTS[table_name]
        for column in frame.columns:
            description, curated = _field_description(table_name, column)
            rows.append(
                {
                    "release_id": release_id,
                    "table_name": table_name,
                    "column_name": column,
                    "description": description,
                    "dtype": str(frame[column].dtype),
                    "nullable": column not in contract.primary_key,
                    "table_description": TABLE_DESCRIPTIONS.get(
                        table_name, "Versioned FDA-scDRS atlas release table."
                    ),
                    "description_status": "curated" if curated else "generated_plain_language",
                }
            )
    dictionary_columns = {
        "release_id": "object",
        "table_name": "object",
        "column_name": "object",
        "description": "object",
        "dtype": "object",
        "nullable": "bool",
        "table_description": "object",
        "description_status": "object",
    }
    for column, dtype in dictionary_columns.items():
        description, curated = _field_description("data_dictionary", column)
        rows.append(
            {
                "release_id": release_id,
                "table_name": "data_dictionary",
                "column_name": column,
                "description": description,
                "dtype": dtype,
                "nullable": column not in TABLE_CONTRACTS["data_dictionary"].primary_key,
                "table_description": TABLE_DESCRIPTIONS["data_dictionary"],
                "description_status": (
                    "curated" if curated else "generated_plain_language"
                ),
            }
        )
    dictionary = pd.DataFrame(rows).sort_values(
        ["table_name", "column_name"], kind="stable"
    ).reset_index(drop=True)
    validate_table("data_dictionary", dictionary)
    return dictionary
